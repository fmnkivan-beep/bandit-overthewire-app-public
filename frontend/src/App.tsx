function renderGlossaryText(text, keyPrefix, onOpen, levelId) {
  const terms = levelId === '1-2' ? ['-'] : Object.keys(GLOSSARY).filter((term) => term !== '-');
  const matcher = new RegExp(`(${terms.sort((a, b) => b.length - a.length).map((term) => term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})`, 'g');
  return text.split(matcher).map((part, index) => (GLOSSARY[part] || GLOSSARY[part.toLowerCase()])
    ? <button key={`${keyPrefix}-term-${index}`} type="button" className="mission-glossary-term" aria-label={`${part}: пояснение`} aria-describedby="mission-glossary-tooltip" onMouseEnter={(event) => onOpen(part.toLowerCase(), event.currentTarget)} onFocus={(event) => onOpen(part.toLowerCase(), event.currentTarget)} onClick={(event) => onOpen(part.toLowerCase(), event.currentTarget, true)}>{part}</button>
    : part);
}

function renderSolutionText(text, safeOnly = false) {
  return text.split(/(`[^`]+`)/g).map((part, index) => {
    if (!part.startsWith('`') || !part.endsWith('`')) return part;
    const value = part.slice(1, -1);
    if (safeOnly && !/^(?:bandit\d+|[A-Z][A-Za-z0-9._-]*|[A-Z]{2,})$/.test(value)) return part;
    return <code key={`solution-code-${index}`}>{value}</code>;
  });
}

