function renderGoalWithHighlights(text, phrases, onOpen, levelId) {
  const matches = phrases
    .map((phrase) => ({ phrase, start: text.indexOf(phrase) }))
    .filter(({ start }) => start >= 0)
    .sort((a, b) => a.start - b.start);
  const parts = [];
  let cursor = 0;

  for (const { phrase, start } of matches) {
    if (start < cursor) continue;
    parts.push(...renderGlossaryText(text.slice(cursor, start), `goal-${cursor}`, onOpen, levelId));
    parts.push(<strong className="mission-goal-emphasis" key={`goal-emphasis-${start}`}>{renderGlossaryText(phrase, `goal-emphasis-${start}`, onOpen, levelId)}</strong>);
    cursor = start + phrase.length;
  }

  parts.push(...renderGlossaryText(text.slice(cursor), `goal-${cursor}`, onOpen, levelId));
  return parts;
}

