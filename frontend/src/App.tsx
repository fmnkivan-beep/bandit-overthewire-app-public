function loadSaved(key, fallback, isValid) {
  try {
    const raw = localStorage.getItem(`otw_bandit_${key}`);
    if (raw === null) return fallback;
    const value = JSON.parse(raw);
    return isValid(value) ? value : fallback;
  } catch {
    return fallback;
  }
}

function isFlagMap(value, keys) {
  return value !== null && typeof value === 'object' && !Array.isArray(value) &&
    Object.entries(value).every(([key, flag]) => keys.includes(key) && typeof flag === 'boolean');
}

function isSavedProgress(value) {
  return value?.version === 1 && ALL_LEVELS.some((level) => level.id === value.activeLevelId) &&
    isFlagMap(value.completed, ALL_LEVELS.map((level) => level.id)) &&
    (value.revision === undefined || Number.isSafeInteger(value.revision) && value.revision >= 0);
}

function loadSavedKeys() {
  return loadSaved('unlocked_keys', [], Array.isArray).filter(isUnlockedKey)
    .filter((key, index, keys) => keys.findIndex((entry) => entry.level === key.level) === index)
    .map(({ level, username, password }) => ({ level, username, password }));
}

function completeUnlockedLevels(completed, keys) {
  const next = { ...completed };
  for (const key of keys) {
    const task = ALL_LEVELS.find((level) => key.level === 0 ? level.id === '0' : level.levelNum === key.level - 1 && level.nextLevelNum === key.level);
    if (task) next[task.id] = true;
  }
  return next;
}

